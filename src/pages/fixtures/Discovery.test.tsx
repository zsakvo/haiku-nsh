  await app.press("id:shelf-entries >> role:button[每日30首]");await app.waitFor("id:page-source-detail");
  await app.waitFor("id:page-source-detail >> text:夜航精选");
  expect(app.shows("text:队列 2 首 · 潮汐之间")).toBe(true);
  await app.keyboard.press("mod+[");
