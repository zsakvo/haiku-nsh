  await app.press("role:button[更多樱华彩的操作]");
  await app.waitFor("text:加入歌单");
  await app.press("text:加入歌单");
  await app.waitFor("role:menuitem[新建歌单…]");
  await app.press("role:menuitem[新建歌单…]");
