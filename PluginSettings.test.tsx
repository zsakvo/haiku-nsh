import { expect, open, test } from "nsh/test";

const options = { platform: "macos" as const, width: 1200, height: 800 };
test("source form verifies against loopback, failed drafts leave no source; developer invokes and Stop detaches", async () => {
  const app = await open("./PluginSettingsFixture.tsx", options);
  await app.waitFor("id:sources-settings");
  const url = app.texts().find(text => /^http:\/\/127\.0\.0\.1:\d+$/.test(text))!;
  expect(!!url).toBe(true);
  await app.press("添加新来源…");
  await app.waitFor("id:source-login");
  await app.type("label:服务器地址", url);
  await app.type("label:用户名", "fixture");
  await app.type("label:密码", "fake-password");
  await app.press("连接并添加");
  await app.waitUntil(() => !app.shows("id:source-login"));
  await app.waitUntil(() => app.texts().some(text => text.includes("127.0.0.1:") && text.endsWith(" · fixture")));
  expect(app.shows("role:button[登录…]")).toBe(false);
  expect(app.shows("role:button[登出]")).toBe(false);
  await app.press("编辑连接…");
  await app.waitFor("text:编辑连接");
  await app.type("label:密码", "fake-password");
  await app.press("验证并保存");
  await app.waitUntil(() => !app.shows("id:source-login"));
  await app.press("读取来源数");
  await app.waitUntil(() => app.texts().some(text => text.startsWith("sources:1;")));
  await app.press("停止订阅");
  const stopped = app.texts().find(text => text.startsWith("stopped:"))!.split(":")[1];
  await app.press("添加新来源…");
  await app.type("label:服务器地址", "http://127.0.0.1:1");
  await app.type("label:用户名", "bad-fixture");
  await app.type("label:密码", "fake-password");
  await app.press("连接并添加");
  await app.waitUntil(() => app.texts().some(text => /UPSTREAM|connect|error/i.test(text)));
  await app.press("role:button[取消]");
  await app.press("读取来源数");
  await app.waitFor(`text:sources:1;commits:${stopped}`);
  await app.press("role:button[插件]");
  await app.waitFor("id:plugins-settings");
  await app.press("role:button[Subsonic 详情]");
  await app.waitFor("text:1 个实例 · 内置插件");
  // Builtin deletion remains unavailable even with the details open.
  expect(app.shows("text:删除插件…")).toBe(true);
  await app.keyboard.press("Escape");
  await app.press("导入…");
  await app.press("HTTPS URL…");
  await app.type("label:文件、目录或 HTTPS URL", "native/app/tests/fixtures/settings-plugin/plugin.ts");
  await app.press("role:button[导入]");
  await app.waitFor("text:Settings fixture");
  await app.press("role:switch[启用Settings fixture]");
  await app.press("读取插件状态");
  await app.waitFor("text:fixture-enabled:false");
  await app.press("role:button[Settings fixture 详情]");
  await app.press("删除插件…");
  await app.waitFor("text:删除插件？");
  await app.press("role:button[取消]");
  expect(app.shows("text:Settings fixture")).toBe(true);
  if (!app.shows("role:button[删除插件…]")) await app.press("role:button[Settings fixture 详情]");
  await app.press("删除插件…");
  await app.press("role:button[删除]");
  await app.waitUntil(() => !app.shows("text:Settings fixture"));
  await app.press("role:button[开发者]");
  await app.type("label:原始 ID", "song:1/字");
  await app.press("role:button[调用]");
  await app.waitFor("id:plugin-call-result");
  await app.waitFor('text:title: "Fixture Song"');
  expect(app.shows("role:button[收起warnings]")).toBe(false);
  expect(app.shows("text:warnings: []")).toBe(true);
});

test("QR expires, refreshes and cancels; SMS cooldown, cookie/web fallback and event Stop", async () => {
  const app = await open("./PluginAuthFixture.tsx", options);
  await app.waitFor("id:login-qr-image");
  await app.waitFor("text:二维码已过期，请刷新");
  expect(app.shows("label:已过期的二维码")).toBe(true);
  await app.press("刷新二维码");
  await app.waitFor("text:请使用手机扫码");
  await app.press("role:button[取消]");
  await app.press("读取来源");
  await app.waitUntil(() => app.texts().some(text => text.startsWith("sources:")));
  const baseline = app.texts().find(text => text.startsWith("sources:"))!;
  await app.press("打开 qrcode");
  await app.press("label:扫码方式");
  await app.press("role:option[等待确认]");
  await app.waitUntil(() => app.texts().some(text => text.includes("QR poll waiting")));
  await app.press("role:button[取消]");
  await app.press("读取来源");
  await app.waitFor(`text:${baseline}`);
  await app.press("打开 sms");
  await app.type("label:手机号", "fixture-phone");
  await app.press("发送验证码");
  await app.waitFor("text:2 秒后重试");
  await app.waitFor("text:发送验证码");
  await app.type("label:验证码", "123456");
  await app.press("连接并添加");
  await app.waitUntil(() => !app.shows("id:source-login"));
  await app.press("打开 cookie");
  await app.type("label:Cookie", "fake-cookie");
  await app.press("连接并添加");
  await app.waitUntil(() => !app.shows("id:source-login"));
  await app.press("打开 web");
  await app.waitUntil(() => app.texts().some(text => text.includes("不支持独立会话")));
  await app.type("label:Cookie", "token=fake-web");
  await app.type("label:登录完成后的 URL", "https://fixture.invalid/done");
  await app.press("连接并添加");
  await app.waitUntil(() => !app.shows("id:source-login"));
  await app.press("触发事件");
  await app.waitUntil(() => app.texts().some(text => /^events:[1-9]/.test(text)));
  await app.press("停止事件订阅");
  const stopped = app.texts().find(text => text.startsWith("stopped:"))!.split(":")[1];
  await app.press("触发事件");
  const until = Date.now() + 400;
  await app.waitUntil(() => Date.now() >= until);
  expect(app.shows(`text:events:${stopped}`)).toBe(true);
});
